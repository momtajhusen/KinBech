export function materialIconName(name) {
  if (typeof name !== 'string') return null;
  const outline = name.endsWith('-outline');
  const pair = MATERIAL[outline ? name.slice(0, -8) : name];
  if (!pair) return null;
  return outline ? pair[1] : pair[0];
}

export default function Icon({ name, ...props }) {
  const material = materialIconName(name);
  if (material) return <MaterialCommunityIcons name={material} {...props} />;
  return <Ionicons name={name} {...props} />;
}
